import type { NativeCursorType } from "@/native/contracts";

/**
 * A single themed cursor image override for one {@link NativeCursorType}.
 *
 * width/height/hotspot are in the same ~32-logical-pixel reference as the built-in
 * PRETTY_NATIVE_CURSOR_ASSETS, so a theme asset matches the default cursor's on-screen
 * size regardless of source PNG resolution. The PNG can be higher-res (e.g. 128x128)
 * and is downscaled at draw time for crisper retina output.
 */
export interface CursorThemeAsset {
	/** Path relative to the public asset root, e.g. "cursors/<id>/arrow.png". */
	assetPath: string;
	width: number;
	height: number;
	hotspotX: number;
	hotspotY: number;
	/** The compositor models this state in 3D (`crates/compositor/src/sculpt.rs`) instead of
	 *  extruding the flat asset, which stays the 2D art. */
	sculpted?: boolean;
}

export interface CursorTheme {
	id: string;
	/** Display label. Proper nouns, so not run through i18n. */
	name: string;
	/** Attribution / origin for the artwork. */
	source?: string;
	/**
	 * Per-cursor-type overrides. Missing types fall back to the built-in default art,
	 * so a pack that only ships "arrow" and "pointer" is complete.
	 */
	assets: Partial<Record<NativeCursorType, CursorThemeAsset>>;
}

/** Sentinel id for the built-in cursor art (no theme override). */
export const DEFAULT_CURSOR_THEME_ID = "default";

/**
 * One sprite as the native compositor consumes it: a path under the public asset root,
 * plus the hotspot as a 0..1 fraction OF THAT IMAGE.
 *
 * The fraction is the whole point of the contract. The compositor scales the sprite to
 * the cursor-size setting, so an offset expressed in the source image's pixels would have
 * to be rescaled at draw time; a fraction survives any scale untouched. Getting this wrong
 * is what made an enlarged cursor drift further and further from what it points at.
 */
export interface CursorSprite {
	/** Path relative to the public asset root, e.g. "cursors/default/arrow.png". */
	assetPath: string;
	/** Hotspot as a fraction of the image width / height. */
	hotspotX: number;
	hotspotY: number;
	/** The compositor's sculpted model for this state in 3D, `"<theme>/<state>"`
	 *  (`crates/compositor/src/sculpt.rs`). Without it, 3D extrudes the sprite. */
	sculpt?: string;
}

